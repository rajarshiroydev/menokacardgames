CREATE TABLE IF NOT EXISTS players (
  id text PRIMARY KEY DEFAULT gen_random_uuid()::text,
  name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 80),
  name_key text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);

ALTER TABLE players
  ADD COLUMN IF NOT EXISTS deleted_at timestamptz;

CREATE INDEX IF NOT EXISTS players_active_name_idx
  ON players (lower(name))
  WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS poker_sessions (
  id text PRIMARY KEY,
  session_number bigint GENERATED BY DEFAULT AS IDENTITY,
  game_name text CONSTRAINT poker_sessions_game_name_length CHECK (
    game_name IS NULL OR char_length(game_name) BETWEEN 1 AND 80
  ),
  played_at timestamptz NOT NULL,
  ended_at timestamptz NOT NULL,
  ante bigint NOT NULL CHECK (ante > 0),
  starting_stack bigint NOT NULL CHECK (starting_stack >= 0),
  hands integer NOT NULL CHECK (hands > 0),
  results jsonb NOT NULL CHECK (
    jsonb_typeof(results) = 'array'
    AND jsonb_array_length(results) BETWEEN 2 AND 10
  ),
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE poker_sessions
  ADD COLUMN IF NOT EXISTS session_number bigint
  GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE poker_sessions
